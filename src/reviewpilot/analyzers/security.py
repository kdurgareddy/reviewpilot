"""Security rules: secrets, injection, unsafe deserialisation, weak crypto, XSS."""

from __future__ import annotations

from ..models import Category, Severity
from .base import Analyzer, Rule, rx

S = Category.SECURITY

RULES = [
    Rule("SEC001", S, Severity.CRITICAL, "Hard-coded AWS access key",
         "An AWS access key ID is committed in source. Anyone with repo access can use it.",
         rx(r"\b(AKIA|ASIA)[0-9A-Z]{16}\b"),
         suggestion="Remove the key, rotate it in IAM now, and load credentials from the environment or a secrets manager.",
         confidence=0.97),
    Rule("SEC002", S, Severity.CRITICAL, "Private key committed",
         "A private key is embedded in the code.",
         rx(r"-----BEGIN (RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----"),
         suggestion="Delete the key from the repo history and rotate it.", confidence=0.98),
    Rule("SEC003", S, Severity.HIGH, "Hard-coded credential",
         "A password, token or API key appears to be assigned a literal value.",
         rx(r"""(?i)\b\w*(password|passwd|pwd|secret|api_?key|access_?token|auth_?token|client_?secret)\w*\b["']?\s*[:=]\s*["'][^"'\s]{8,}["']"""),
         exclude=rx(r"""(?i)(example|changeme|placeholder|dummy|xxx|\*\*\*|<|\$\{|os\.environ|getenv|process\.env|your[_-])"""),
         suggestion="Read the value from an environment variable or secrets manager instead.", confidence=0.8,
         skip_tests=True),
    Rule("SEC015", S, Severity.CRITICAL, "Live API secret committed",
         "A live secret key for a third-party service is committed in source.",
         rx(r"\b(sk_live_[0-9a-zA-Z]{16,}|rk_live_[0-9a-zA-Z]{16,}|ghp_[0-9A-Za-z]{36}|github_pat_\w{40,}|xox[baprs]-[0-9A-Za-z-]{10,}|AIza[0-9A-Za-z_-]{35}|sk-[A-Za-z0-9_-]{32,})"),
         suggestion="Revoke the key with the provider now, then load it from the environment.", confidence=0.97),
    Rule("SEC004", S, Severity.CRITICAL, "SQL built from string formatting",
         "The query is assembled with string formatting or concatenation, which allows SQL injection.",
         rx(r"""(?i)\b(execute|executemany|raw|query|exec)\s*\((?=[^)]*(\bf["']|["']\s*\+|\+\s*["']|["']\s*%\s*[\w(]|["']\.format\())"""),
         suggestion='Use parameters: cursor.execute("SELECT * FROM users WHERE id = %s", (user_id,))',
         confidence=0.9),
    Rule("SEC004", S, Severity.CRITICAL, "SQL built from string formatting",
         "The SQL string is built by interpolating values, which allows SQL injection when it is executed.",
         rx(r"""(?i)^\s*\w+\s*[+]?=\s*(f(?P<q1>["'])(?:(?!(?P=q1)).)*\b(select|insert\s+into|update|delete\s+from)\b(?:(?!(?P=q1)).)*\{|(?P<q2>["'])(?:(?!(?P=q2)).)*\b(select|insert\s+into|update|delete\s+from)\b(?:(?!(?P=q2)).)*(?P=q2)\s*(\+|%\s*[\w(]|\.format\())"""),
         languages=("python",),
         suggestion="Keep placeholders in the SQL and pass values separately to execute().", confidence=0.85),
    Rule("SEC005", S, Severity.CRITICAL, "SQL string concatenation",
         "Values are concatenated or interpolated into a SQL string, which allows SQL injection.",
         rx(r"""(?i)["'`]\s*(select|insert\s+into|update|delete\s+from)\b.*["'`]\s*\+\s*\w|`[^`]*\b(select|insert\s+into|update|delete\s+from)\b[^`]*\$\{"""),
         languages=("javascript", "typescript", "java", "csharp", "php", "go", "kotlin"),
         suggestion="Use a parameterised query or prepared statement.", confidence=0.88),
    Rule("SEC006", S, Severity.HIGH, "Use of eval/exec",
         "eval/exec runs arbitrary code; with any user-controlled input this is remote code execution.",
         rx(r"(?<![\w.])(eval|exec)\s*\("), languages=("python", "javascript", "typescript", "php", "ruby"),
         exclude=rx(r"ast\.literal_eval|\.exec\(\s*\)|regex|RegExp|\.exec\(\w+\)\s*[;)]?$"),
         suggestion="Parse the input explicitly (e.g. json.loads or ast.literal_eval) instead of evaluating it.",
         confidence=0.82),
    Rule("SEC007", S, Severity.HIGH, "Shell command with shell=True / os.system",
         "Running a shell with an interpolated string allows command injection.",
         rx(r"shell\s*=\s*True|os\.system\s*\(|os\.popen\s*\(|child_process\.exec\s*\(|\bexecSync\s*\(\s*`"),
         suggestion="Pass an argument list without a shell: subprocess.run(['ls', path], check=True)",
         confidence=0.85),
    Rule("SEC008", S, Severity.HIGH, "Unsafe deserialisation",
         "Deserialising untrusted data with pickle or yaml.load can execute arbitrary code.",
         rx(r"pickle\.loads?\s*\(|cPickle\.loads?\s*\(|yaml\.load\s*\((?![^)]*SafeLoader)|marshal\.loads\s*\("),
         languages=("python",), suggestion="Use json, or yaml.safe_load for YAML.", confidence=0.86),
    Rule("SEC009", S, Severity.MEDIUM, "Weak hash for sensitive data",
         "MD5 and SHA-1 are broken for passwords, signatures and integrity checks.",
         rx(r"(?i)(hashlib\.(md5|sha1)\s*\(|MessageDigest\.getInstance\(\s*\"(MD5|SHA-?1)\"|createHash\(\s*['\"](md5|sha1)['\"])"),
         suggestion="Use bcrypt/argon2 for passwords, or SHA-256+ (hashlib.sha256) for integrity.",
         confidence=0.75),
    Rule("SEC010", S, Severity.HIGH, "TLS verification disabled",
         "Disabling certificate verification exposes the connection to man-in-the-middle attacks.",
         rx(r"verify\s*=\s*False|rejectUnauthorized\s*:\s*false|NODE_TLS_REJECT_UNAUTHORIZED\s*=\s*['\"]?0|InsecureSkipVerify\s*:\s*true"),
         suggestion="Keep verification on; point it at the right CA bundle if needed.", confidence=0.9),
    Rule("SEC011", S, Severity.HIGH, "JWT signature not verified",
         "Decoding a JWT without verifying its signature lets anyone forge tokens.",
         rx(r"""verify_signature["']?\s*:\s*False|algorithms\s*=\s*\[\s*["']none["']|jwt\.decode\([^)]*verify\s*=\s*False"""),
         suggestion="Always verify: jwt.decode(token, key, algorithms=['HS256'])", confidence=0.9),
    Rule("SEC012", S, Severity.HIGH, "Possible XSS sink",
         "Assigning unsanitised content to innerHTML / dangerouslySetInnerHTML allows cross-site scripting.",
         rx(r"\.innerHTML\s*[+]?=(?!\s*['\"`]\s*['\"`]?\s*;?\s*$)|dangerouslySetInnerHTML|document\.write\s*\(|\|\s*safe\b|mark_safe\s*\("),
         languages=("javascript", "typescript", "python", "text"),
         suggestion="Use textContent, or sanitise with a library such as DOMPurify.", confidence=0.78),
    Rule("SEC013", S, Severity.MEDIUM, "Debug mode enabled",
         "Running with debug mode on can expose stack traces and an interactive console in production.",
         rx(r"(?i)\bdebug\s*=\s*True\b|app\.run\([^)]*debug\s*=\s*True"), languages=("python",),
         exclude=rx(r"(?i)os\.environ|getenv"), skip_tests=True,
         suggestion="Read debug mode from configuration and default it to False.", confidence=0.7),
    Rule("SEC014", S, Severity.MEDIUM, "Wildcard CORS",
         "Allowing every origin with credentials lets any website call this API as the user.",
         rx(r"""allow_origins\s*=\s*\[\s*["']\*["']\s*\]|Access-Control-Allow-Origin["']?\s*[,:]\s*["']\*|origin\s*:\s*["']\*["']"""),
         suggestion="List the allowed origins explicitly.", confidence=0.65),
]


def make() -> Analyzer:
    return Analyzer("security", S, list(RULES))
